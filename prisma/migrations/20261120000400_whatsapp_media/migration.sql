CREATE TABLE whatsapp_media (
  id VARCHAR(64) PRIMARY KEY, mime VARCHAR(64) NOT NULL, filename VARCHAR(120) NOT NULL,
  content LONGBLOB NOT NULL
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
ALTER TABLE whatsapp_jobs ADD mediaId VARCHAR(64) NULL,
  ADD FOREIGN KEY(mediaId) REFERENCES whatsapp_media(id) ON DELETE RESTRICT ON UPDATE CASCADE;
